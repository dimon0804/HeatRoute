def set_text(shape, lines, color=None, size=None,
             head_color=None, head_size=None, head_bold=None):
    """Текст в фигуру с сохранением оформления шаблона.

    Все абзацы делаются копиями первого: в шаблоне второй и третий абзацы
    плейсхолдера нередко залиты бледным «затухающим» цветом, и наследовать его
    для содержательного текста незачем.
    """
    tf = shape.text_frame
    origin = copy.deepcopy(tf.paragraphs[0]._p)
    body = tf._txBody
    for paragraph in list(tf.paragraphs):
        body.remove(paragraph._p)
    for _ in lines:
        body.append(copy.deepcopy(origin))

    for index, (paragraph, line) in enumerate(zip(tf.paragraphs, lines)):
        runs = paragraph.runs
        if runs:
            runs[0].text = line
            for extra in runs[1:]:
                extra._r.getparent().remove(extra._r)
        else:
            paragraph.text = line
        first = index == 0 and head_color is not None
        for run in paragraph.runs:
            if first:
                run.font.color.rgb = head_color
                if head_size:
                    run.font.size = Pt(head_size)
                if head_bold is not None:
                    run.font.bold = head_bold
                continue
            if color is not None:
                run.font.color.rgb = color
            if size is not None:
                run.font.size = Pt(size)


def drop_data_labels(chart):
    """Снять подписи точек, настроенные в шаблоне под его собственные данные."""
    tag = '{http://schemas.openxmlformats.org/drawingml/2006/chart}dLbls'
    for element in chart._chartSpace.iter(tag):
        element.getparent().remove(element)


def picture_box(slide, placeholder, image, anchor='center'):
    """Картинка ровно в габарит блока макета, с обрезкой по его пропорциям.

    Плейсхолдер снимается, а картинка кладётся отдельной фигурой: вставка внутрь
    плейсхолдера уводит её в другое место слайда, а пустой он печатается серым
    прямоугольником. По ширине берётся левая часть — у карты там трасса, легенда
    остаётся на слайде с полной картой. По высоте обрезка либо от середины, либо
    от верха: у снимка панели верх содержательный, а низ пустой.
    """
    if not os.path.exists(image):
        return
    from PIL import Image
    box = (placeholder.left, placeholder.top, placeholder.width, placeholder.height)
    drop(slide, placeholder)
    source = Image.open(image)
    target = box[2] / box[3]
    width = min(source.width, int(round(source.height * target)))
    height = min(source.height, int(round(width / target)))
    top = 0 if anchor == 'top' else (source.height - height) // 2
    cropped = source.crop((0, top, width, top + height))
    handle, path = tempfile.mkstemp(suffix='.png')
    os.close(handle)
    try:
        cropped.save(path)
        slide.shapes.add_picture(path, box[0], box[1], box[2], box[3])
    finally:
        os.unlink(path)


def named(slide, name):
    for shape in slide.shapes:
        if shape.name == name:
            return shape
    raise LookupError('нет фигуры %r на слайде' % name)


def at(slide, top, left=None, tol=0.1):
    """Фигура по положению: на слайдах 8–10 все текстовые боксы зовутся одинаково."""
    for shape in slide.shapes:
        if not shape.has_text_frame or shape.top is None:
            continue
        if abs(shape.top / EMU - top) > tol:
            continue
        if left is not None and abs(shape.left / EMU - left) > tol:
            continue
        return shape
    raise LookupError('нет текстовой фигуры на y=%.2f' % top)


def drop(slide, shape):
    shape._element.getparent().remove(shape._element)


def title(slide, name, text, pill=True):
    """Заголовок и подгонка плашки под его длину, как это сделано в шаблоне."""
    set_text(named(slide, name), [text])
    if not pill:
        return
    for shape in slide.shapes:
        if shape.top is None or shape.left is None:
            continue
        if not shape.name.startswith('Скругленный прямоугольник'):
            continue
        if abs(shape.left / EMU - 0.38) < 0.03 and abs(shape.top / EMU - 0.35) < 0.08:
            shape.width = Inches(min(12.4, max(1.9, 0.55 + 0.262 * len(text))))
            return


def clear_layout_prompts(prs):
    """Подсказки пустых плейсхолдеров макетов не должны попадать в печать."""
    for layout in prs.slide_layouts:
        for shape in layout.placeholders:
            if shape.has_text_frame and shape.text_frame.text.strip():
                shape.text_frame.clear()
                for paragraph in shape.text_frame.paragraphs:
                    for run in paragraph.runs:
                        run.text = ''


def renumber(prs):
    """Номера слайдов: часть из них в шаблоне вписана текстом, а не полем."""
    for index, slide in enumerate(prs.slides, start=1):
        for shape in slide.shapes:
            if not shape.name.startswith('Номер слайда') or not shape.has_text_frame:
                continue
            if 'slidenum' in shape._element.xml:
                continue                       # поле, PowerPoint посчитает сам
            set_text(shape, [str(index)])


def to_pdf(source):
    """PDF снимается из того же файла, а не готовится отдельно.

    Две презентации, собранные по отдельности, рано или поздно расходятся,
    а на сдачу уходят обе.
    """
    binaries = ['soffice', r'C:\Program Files\LibreOffice\program\soffice.com']
    for binary in binaries:
        try:
            subprocess.run([binary, '--headless', '--convert-to', 'pdf',
                            '--outdir', os.path.dirname(source), source],
                           check=True, capture_output=True)
            return os.path.splitext(source)[0] + '.pdf'
        except (OSError, subprocess.CalledProcessError):
            continue
    raise SystemExit('LibreOffice не найден: PDF снять нечем. '
                     'Установите его или снимите PDF вручную.')


