package ru.lct.heatroute.domain.reference;

/** Правило учёта пространственного ограничения (таблица 5.1 ТП). */
public enum RestrictionRule {

    /** Пересечение запрещено: сеть обходит объект с минимальным горизонтальным расстоянием. */
    FORBIDDEN,

    /** Пересечение допускается специальным проходом с коэффициентом стоимости Kспец. */
    SPECIAL_CROSSING
}
