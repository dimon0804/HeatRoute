package ru.lct.heatroute.domain.result;

import lombok.Builder;
import lombok.Value;
import org.locationtech.jts.geom.Point;

/**
 * Присоединение независимой части новой сети к существующей.
 * <p>
 * Отдельным объектом выгрузки это больше не является: раздел 2.4 ТП в редакции
 * от 18.09 говорит прямо — «отдельный геообъект места присоединения не формируется»,
 * а разъяснение №13 добавляет, что и объект {@code tie_in} не формируется.
 * Запись осталась внутренней: по ней считается стоимость врезок, строится отпечаток
 * варианта и объясняется в интерфейсе, куда именно часть сети присоединена.
 */
@Value
@Builder(toBuilder = true)
public class TieInResult {

    String id;
    String variantId;
    Point location;

    /** ID существующего участка или камеры, к которой присоединена новая сеть. */
    String existingObjectId;

    /** {@code heat_network} или {@code heat_chamber}. */
    String existingObjectType;

    /** Условный диаметр существующего объекта, мм. */
    int existingDiameter;

    /** Доля длины существующего участка до точки присоединения — для отпечатка варианта. */
    double positionFraction;

    /**
     * Сколько врезок оплачивается по разделу 3.2: каждый новый линейный участок,
     * заканчивающийся в существующей тепловой камере, считается отдельной врезкой.
     * Если в месте присоединения строится новая камера, врезок ноль — присоединение
     * уже включено в стоимость камеры.
     */
    int tieInCount;

    /** Стоимость врезок этого присоединения, руб. */
    double cost;
}
