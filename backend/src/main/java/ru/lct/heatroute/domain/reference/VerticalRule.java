package ru.lct.heatroute.domain.reference;

/** Правило взаимного положения новой сети и объекта по глубине (таблица 2 ТП). */
public enum VerticalRule {

    /** Только под объектом: верх габарита новой сети ниже заданной отметки от поверхности. */
    BELOW_SURFACE,

    /** Допускается и выше, и ниже коммуникации при соблюдении вертикального просвета. */
    ABOVE_OR_BELOW
}
