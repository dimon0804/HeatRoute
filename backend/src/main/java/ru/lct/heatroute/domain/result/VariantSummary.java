package ru.lct.heatroute.domain.result;

import lombok.Builder;
import lombok.Value;
import lombok.With;

import java.util.List;
import java.util.Map;

/**
 * Сводная информация по варианту (раздел 7.2 ТП в редакции от 18.09). В выгрузке идёт
 * одной записью с {@code geometry = null} и содержит только итоговые показатели.
 * <p>
 * Состав полей сократился вместе с расчётной моделью: реконструкции существующей сети
 * и существующих камер в ней больше нет, поэтому ушли {@code reconstruction_cost},
 * {@code chamber_reconstruction_cost}, {@code reconstruction_length} и суммарная
 * {@code length}. Стоимость врезок теперь относится только к существующим камерам
 * и сопровождается их количеством.
 */
@Value
@Builder(toBuilder = true)
public class VariantSummary {

    String id;
    String variantId;

    /** Место в ранжировании: 1 — лучший вариант. */
    @With
    int rank;

    /**
     * Стоимость строительства: новые участки тепловой сети, новые тепловые камеры
     * и врезки в существующие тепловые камеры (раздел 6 ТП).
     */
    double constructionCost;

    /** Стоимость строительства новых тепловых камер, входящая в стоимость строительства. */
    double chamberConstructionCost;

    /**
     * Количество врезок в существующие тепловые камеры. Каждый новый участок,
     * заканчивающийся в существующей камере, — отдельная врезка (раздел 3.2 ТП).
     */
    int existingChamberTieInCount;

    /** Стоимость врезок в существующие тепловые камеры, входящая в стоимость строительства. */
    double existingChamberTieInCost;

    /** Штраф за неподключённые точки подключения, руб. */
    double unconnectedPenalty;

    /** Итоговая стоимость варианта: стоимость строительства плюс штраф, руб. */
    double calculatedCost;

    /** Суммарная длина новых участков тепловой сети, м. */
    double newNetworkLength;

    /** Итоговый показатель S раздела 6 ТП: чем меньше, тем выше вариант. */
    double score;

    /**
     * ID точек подключения, для которых маршрут не найден.
     * <p>
     * Раздел 7.2 требует сохранять тип идентификатора таким же, как во входных данных:
     * если на входе пришло число, в выгрузке должно быть число, а не строка. Поэтому
     * здесь хранится не {@code String}, а исходное значение.
     */
    List<Object> unconnectedOksIds;

    /**
     * Те же точки, но идентификаторами в том виде, в каком расчёт с ними работает —
     * строками. Внутри сервиса по этим ключам ищется расход точки и причина отказа,
     * а наружу уходит {@link #unconnectedOksIds} с исходным типом. Два списка вместо
     * одного именно поэтому: контракт выгрузки требует сохранить тип, а расчёту нужен
     * стабильный ключ.
     */
    List<String> unconnectedPointKeys;

    /**
     * Почему каждая из них осталась без подключения: ID → причина по-русски.
     * <p>
     * Список идентификаторов без объяснения бесполезен: раздел 2.9 ТЗ требует
     * обработать такой случай, а обработать — значит не только назвать объект,
     * но и сказать, что с ним не так. Причина известна ровно там, где объект
     * выбывает, и дальше её остаётся донести.
     */
    Map<String, String> unconnectedReasons;
}
