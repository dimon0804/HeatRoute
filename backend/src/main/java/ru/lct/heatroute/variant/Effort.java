package ru.lct.heatroute.variant;

import lombok.Value;

/**
 * Итог улучшающего прохода: что выиграно и сколько ходов при этом проверено.
 * <p>
 * Второе число нужно не для отчётности. Главный вопрос к любой эвристике —
 * «а вдруг рядом есть лучше»; ответить на него можно только перечислив, что именно
 * было проверено и отвергнуто. Поэтому число проверенных ходов последнего прохода,
 * не давшего улучшения, доходит до показателей расчёта: это и есть сертификат
 * локальной оптимальности решения.
 */
@Value
public class Effort {

    /** Выигрыш прохода: метры у перецепки, рубли у переноса развилок. Ноль — улучшений нет. */
    double gain;

    /**
     * Сколько ходов проверено в последнем проходе, который улучшения не дал.
     * Именно последний: ходы предыдущих проходов проверялись на другом дереве
     * и о текущем решении ничего не говорят.
     */
    int movesVerified;
}
