package ru.lct.heatroute.variant;

import lombok.Builder;
import lombok.Value;
import lombok.With;
import org.locationtech.jts.geom.Coordinate;

/**
 * Возможное место присоединения новой сети к существующей.
 * <p>
 * Раздел 8.2 ТП делит все места врезки на два случая, и решение принимается здесь,
 * а не при расчёте стоимости: если точка не далее 10 м от существующей камеры и после
 * подключения к камере будет примыкать не более четырёх участков — врезка выполняется
 * в этой камере; иначе в точке врезки строится новая камера. Разница в стоимости
 * от 3 до 12 млн руб., поэтому сравнение кандидатов без этого признака бессмысленно.
 */
@Value
@Builder(toBuilder = true)
public class TieInCandidate {

    /** Служебный идентификатор кандидата в пределах расчёта. */
    String id;

    /** Положение врезки в рабочей проекции. */
    Coordinate location;

    /** ID существующего объекта, в который выполняется врезка. */
    String existingObjectId;

    /** {@code heat_network} или {@code heat_chamber} — значения раздела 10.2 ТП. */
    String existingObjectType;

    /** Условный диаметр существующего объекта в точке врезки, мм. */
    int existingDiameter;

    /**
     * Доля длины существующего участка до точки врезки, {@code [0, 1]}.
     * Нужна для частичной реконструкции: при врезке внутри участка дополнительный
     * расход действует только на часть от точки врезки в сторону источника (раздел 7 ТП).
     */
    double positionFraction;

    /** Врезка выполняется в существующую камеру, новая камера не строится. */
    boolean usesExistingChamber;

    /** ID существующей камеры, если врезка в неё. */
    String existingChamberId;

    /** Сколько участков уже примыкает к существующей камере. */
    int chamberExistingDegree;

    /** Индекс узла в графе маршрутизации; проставляется после построения графа. */
    @With
    int graphNodeIndex;
}
