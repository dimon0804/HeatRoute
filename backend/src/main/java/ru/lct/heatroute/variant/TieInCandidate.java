package ru.lct.heatroute.variant;

import lombok.Builder;
import lombok.Value;
import lombok.With;
import org.locationtech.jts.geom.Coordinate;

/**
 * Возможное место присоединения новой сети к существующей.
 * <p>
 * Раздел 2.4 ТП делит все места присоединения на два случая, и решение принимается
 * здесь, а не при расчёте стоимости: если точка не далее 10 м от существующей камеры
 * и после подключения к камере будет примыкать не более четырёх участков — новая сеть
 * заходит в эту камеру и каждый её участок платит врезку; иначе в выбранной точке
 * существующего участка строится новая камера, и присоединение уже включено в её
 * стоимость. Разница в стоимости от 3 до 12 млн руб., поэтому сравнение кандидатов
 * без этого признака бессмысленно.
 */
@Value
@Builder(toBuilder = true)
public class TieInCandidate {

    /** Служебный идентификатор кандидата в пределах расчёта. */
    String id;

    /** Положение врезки в рабочей проекции. */
    Coordinate location;

    /** ID существующего объекта, в который выполняется врезка. */
    String existingObjectId;

    /** {@code heat_network} или {@code heat_chamber} — значения раздела 7.1 ТП. */
    String existingObjectType;

    /** Условный диаметр существующего объекта в точке врезки, мм. */
    int existingDiameter;

    /**
     * Доля длины существующего участка до места присоединения, {@code [0, 1]}.
     * Нужна для отпечатка варианта: два решения, присоединённые к одному участку
     * в разных его местах, — это разные решения, и различать их надо.
     */
    double positionFraction;

    /** Врезка выполняется в существующую камеру, новая камера не строится. */
    boolean usesExistingChamber;

    /** ID существующей камеры, если врезка в неё. */
    String existingChamberId;

    /** Сколько участков уже примыкает к существующей камере. */
    int chamberExistingDegree;

    /** Индекс узла в графе маршрутизации; проставляется после построения графа. */
    @With
    int graphNodeIndex;
}
