package ru.lct.heatroute.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Builder;
import lombok.Value;

/** Показатели прогона — нужны, чтобы объяснить, как получен результат. */
@Value
@Builder
@Schema(description = "Показатели прогона расчёта")
public class JobStatsDto {

    @Schema(description = "Условный диаметр, по которому рассчитаны клиренсы, мм", example = "400")
    int designDiameter;

    @Schema(description = "Узлов в графе маршрутизации", example = "3180")
    int graphNodes;

    @Schema(description = "Рёбер в графе маршрутизации", example = "61843")
    int graphEdges;

    @Schema(description = "Рассмотрено кандидатов точек врезки", example = "78")
    int tieInCandidates;

    @Schema(description = "Время расчёта, мс", example = "20791")
    long millis;

    /**
     * Показатель соответствия, а не производительности: сколько вершин трассы не удалось
     * привести к пределу угла поворота 90° из раздела 2.1 приложения. Ноль — норма.
     * Величина видна наружу намеренно: нарушение предела надо показывать, а не прятать
     * в журнале сервиса.
     */
    @Schema(description = "Вершин, не приведённых к пределу угла поворота 90°", example = "0")
    int sharpTurns;

    /**
     * Участков, для которых в режиме с учётом глубины не нашлось допустимого профиля.
     * Ноль — все пересечения решены с требуемым просветом.
     */
    @Schema(description = "Участков без допустимого профиля по глубине", example = "0")
    int depthUnresolved;

    /**
     * Сколько одиночных ходов улучшения проверено на итоговом дереве лучшего варианта
     * без того, чтобы хоть один его улучшил. Это ответ на главный вопрос к эвристике:
     * «а вдруг рядом есть решение лучше». Гарантии глобального оптимума нет и быть
     * не может, но локальная оптимальность решения этим числом подтверждается.
     */
    @Schema(description = "Ходов улучшения проверено без успеха на лучшем варианте",
            example = "1240")
    int verifiedMoves;
}
