package ru.lct.heatroute.routing;

import lombok.Data;
import org.springframework.boot.context.properties.ConfigurationProperties;

/** Параметры построения свободного пространства и графа маршрутизации. */
@Data
@ConfigurationProperties(prefix = "heatroute.routing")
public class RoutingProperties {

    /**
     * Условный диаметр, по которому строятся клиренсы графа маршрутизации.
     * Ноль — значение по умолчанию: диаметр берётся по суммарному расходу всех
     * перспективных ОКС, то есть по ДУ магистрали. Маршрут, допустимый для него,
     * допустим и для любого меньшего, поэтому нарушение нормы невозможно
     * по построению (раздел 1.1 документа по алгоритму).
     * <p>
     * Оптимистичный диаметр с последующей проверкой клиренсов там же рассмотрен
     * и отвергнут: он требует перестроения подграфа после каждого расчёта диаметров
     * и не гарантирует сходимости. Ненулевое значение здесь — способ посмотреть,
     * что будет при других клиренсах, не пересобирая сервис; порядок источников
     * в {@code VariantPlanner}: запрос важнее этого параметра, параметр важнее
     * расчёта по суммарному расходу.
     */
    private int initialDesignDn = 0;


    /**
     * Радиус видимости между вершинами препятствий, м. Рёбра длиннее не строятся:
     * на плотной застройке прямая видимость всё равно перекрыта, а число проверок
     * растёт квадратично. Длинный прямой участок при этом не теряется — он проходит
     * через промежуточные вершины и восстанавливается спрямлением коллинеарных звеньев.
     */
    private double visibilityRadius = 300;

    /**
     * Радиус видимости для рёбер, инцидентных терминалам и кандидатам врезки, м.
     * Таких узлов десятки, а не тысячи, поэтому им дан полный обзор: точка подключения
     * может стоять в 480 м от сети, и терять прямой выход к ней нельзя.
     */
    private double terminalVisibilityRadius = 2000;

    /** Отступ от концов ребра при проверке проходимости, м. */
    private double edgeEndEpsilon = 0.01;

    /** Радиус поиска кандидатов врезки вокруг точки подключения ОКС, м. */
    private double tieInSearchRadius = 1200;

    /** Шаг дискретизации существующей сети при поиске точек врезки, м. */
    private double tieInSampleStep = 25;

    /**
     * Угол, ниже которого поворот трассы считается незначимым и спрямляется, град.
     * Борьба с «случайной мелкой ломаной» из критериев оценки.
     */
    private double minTurnAngleDeg = 3.0;

    /**
     * Проверять ли минимальное горизонтальное расстояние при проходе рядом со
     * специальным объектом — дорогой, трамвайными путями, газопроводом, кабелем,
     * существующей теплосетью. Раздел 4 ТП этого требует, и по умолчанию проверка
     * включена. Выключатель оставлен на случай, когда проверочный набор окажется
     * настолько плотным, что коридоры между специальными объектами перестанут
     * проходиться: подключить ОКС с оговоркой полезнее, чем не подключить вовсе.
     */
    private boolean enforceSpecialClearance = true;

    /**
     * Сколько метров хода внутри зоны отступа специального объекта считать неизбежным
     * примыканием, а не прохождением рядом, м. Выход из места присоединения к существующей
     * сети и заход к точке подключения неизбежно задевают такие зоны на считанные метры;
     * проход вдоль объекта тянется в зоне долго, и различать их надо по длине, а не
     * по самому факту захода.
     */
    private double specialAlongsideToleranceM = 3.0;

    /**
     * Сколько точек врезки проходят полную оценку на каждую часть сети.
     * <p>
     * Кандидатов десятки, и строить дерево для каждого дорого. Сначала все они
     * оцениваются снизу — суммой расстояний в графе до терминалов группы, — и в полную
     * проверку уходят только лучшие. Оценка честная: дерево Штейнера не короче
     * наибольшего из этих расстояний и не длиннее их суммы, поэтому порядок
     * по ней близок к порядку по стоимости.
     */
    private int tieInShortlistSize = 12;

    /**
     * Сколько раз эвристика Штейнера запускается с разными затравочными терминалами.
     * <p>
     * Порядок подключения меняет форму дерева; из нескольких форм берётся кратчайшая,
     * а дерево, оставившее объекты без подключения, штрафуется так, что проигрывает
     * любому связному. Сравнение именно по длине, а не по стоимости: стоимость здесь
     * потребовала бы материализации каждой пробы — подбора диаметров, предельных длин
     * и технических узлов, — а формы сравниваются между собой при одном и том же
     * составе подключённых объектов, где длина решает то же самое дешевле.
     */
    private int steinerRestarts = 8;

    /**
     * На сколько независимых частей максимум пробовать делить перспективные ОКС.
     * Каждое разбиение даёт кандидата в варианты и стоит времени расчёта.
     * <p>
     * Замер 18.09 на конкурсном наборе и первой редакции приложения: три разбиения —
     * 20 с, четыре — 26 с, пять — 29 с, при этом лучший вариант во всех случаях один
     * и тот же, меняются только второй и третий. Показатель той редакции с текущим
     * не сравнивается: в него входила реконструкция. Взято три; на наборе с другой
     * географией имеет смысл поднять, не пересобирая сервис.
     */
    private int maxOksPartitions = 3;

    /**
     * Сколько вариантов достраивается затравками, если разбиения ОКС дали меньше трёх
     * содержательно разных решений.
     * <p>
     * Разбиения — основной источник различий, но на наборе, где все ОКС лежат одной
     * гроздью, разбиение ровно одно, и трёх вариантов из него не получится. Тогда
     * различие даёт форма дерева: эвристика запускается с другого затравочного
     * терминала и строит другую сеть при той же точке врезки. На конкурсном наборе
     * этот запас не нужен и не тратится — разбиения дают три варианта сами.
     */
    private int seededVariantAttempts = 4;

    /**
     * Сколько раз чередуются два хода доводки дерева: перецепка ветви и перенос
     * развилки в точку Ферма.
     * <p>
     * Ходы связаны — перецепленная ветвь меняет оптимальное положение развилки,
     * а сдвинутая развилка меняет, куда выгодно цеплять ветвь, — поэтому одного
     * прохода каждым мало. Круги идут, пока есть выигрыш, но не больше этого числа:
     * на конкурсном наборе выигрыш исчерпывается за два-три.
     */
    private int treePolishRounds = 4;

    /**
     * Сколько раз трасса перекладывается по замечаниям профиля по глубине.
     * <p>
     * Проход — это повторное построение варианта с зонами запрета вокруг пересечений,
     * где манёвр не поместился; зоны накапливаются, поэтому каждый следующий строже
     * предыдущего. Стоит проход около двух секунд: граф маршрутизации переиспользуется,
     * а запреты действуют маской его рёбер, которая считается один раз на часть сети.
     * <p>
     * По умолчанию один. На конкурсном наборе единственное нарушение просвета
     * перекладкой не снимается — оно приходится на первые метры от врезки, где разбегу
     * взяться неоткуда, — и второй с третьим проходом только тратят время. На наборе
     * с другой геометрией имеет смысл поднять, не пересобирая сервис.
     */
    private int depthRelayPasses = 1;

    /**
     * Предел времени на один вариант, с. Ноль и меньше — без предела.
     * <p>
     * Тратится он на перебор: точки врезки, формы дерева, круги доводки. Начатый вариант
     * всегда достраивается, поэтому предел сужает поиск, а не обрывает расчёт: на чужом
     * наборе лучше получить решение, найденное грубее, чем ждать без конца. Проверяется
     * предел на границах шагов перебора, так что фактическое время может превысить его
     * на один шаг; срабатывание пишется в журнал.
     * <p>
     * По умолчанию две минуты: конкурсный набор считается около двадцати секунд на все
     * три варианта, то есть запас шестикратный и на нём предел не срабатывает ни разу.
     */
    private long variantTimeBudgetSeconds = 120;
}
