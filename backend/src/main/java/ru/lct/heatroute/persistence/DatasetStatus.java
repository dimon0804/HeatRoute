package ru.lct.heatroute.persistence;

/** Состояние загруженного набора. */
public enum DatasetStatus {

    /** Файл принят, разбор ещё идёт. */
    PARSING,

    /** Разбор завершён, набор готов к расчёту. */
    READY,

    /** Разбор завершён, но данные непригодны для расчёта: причина в протоколе. */
    INVALID,

    /** Разбор не удался: формат файла не GeoJSON или файл повреждён. */
    FAILED
}
