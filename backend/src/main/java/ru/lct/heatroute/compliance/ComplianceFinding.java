package ru.lct.heatroute.compliance;

import lombok.Value;

import java.util.List;

/**
 * Одно нарушение: какое правило не выполнено, где именно и чем это видно.
 * <p>
 * Идентификаторы объектов обязательны. Отчёт без них бесполезен: «где-то нарушена
 * предельная длина» проверить нельзя, а «на пути от точки 7 через участки new_v1_3
 * и new_v1_4 накопилось 1 180 м при пределе 1 042» — можно.
 */
@Value
public class ComplianceFinding {

    ComplianceRule rule;

    /** Вариант, к которому относится нарушение; пусто, если оно про файл целиком. */
    String variantId;

    /** Объекты выгрузки или входного набора, которыми нарушение подтверждается. */
    List<String> objectIds;

    /** Что именно не сошлось, с числами. */
    String detail;
}
