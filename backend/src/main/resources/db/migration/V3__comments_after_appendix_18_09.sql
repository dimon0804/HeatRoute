-- =====================================================================================
--  Подписи к таблицам приводятся к редакции технического приложения от 18.09.
--
--  Отдельной миграцией, а не правкой V1 и V2: Flyway поднят с validateOnMigrate,
--  и изменение уже применённой миграции меняет её контрольную сумму — сервис
--  перестал бы стартовать на любой базе, где V1 и V2 уже прошли.
--
--  Что именно разошлось с действительностью:
--
--  Нумерация. Состав выгрузки в первой редакции описывал раздел 10, в новой — 7.1.
--
--  Типы объектов. Объекта tie_in в выгрузке больше нет: место присоединения
--  к существующей сети выражается тепловой камерой, а не отдельным типом.
--  Типов ровно четыре — heat_network, heat_chamber, technical_node,
--  variant_summary.
--
--  Z-координаты. V2 сняла с колонки требование двумерности, и это по-прежнему
--  нужно: колонка общая для плоского расчёта и расчёта по глубине. Но подпись
--  обещала Z в базе, а их там нет — отметки снимаются перед записью и в файл,
--  и в базу, потому что раздел 7.1 их не предусматривает.
-- =====================================================================================

COMMENT ON TABLE variant_feature IS
    'Объекты выходного GeoJSON по разделу 7.1 ТП, по одному на строку';

COMMENT ON COLUMN variant_feature.object_type IS
    'Тип объекта раздела 7.1 ТП: heat_network, heat_chamber, technical_node, variant_summary';

COMMENT ON COLUMN variant_feature.geom IS
    'Геометрия в WGS 84, без Z-координат; у сводной записи варианта её нет';
