-- =====================================================================================
--  Геометрия результата должна принимать Z-координаты.
--
--  Дополнительная задача кейса — трассировка с учётом глубины — выгружает геометрию
--  с отметками Z, а колонка была объявлена как geometry(Geometry,4326), то есть
--  строго двумерная, и PostGIS отклонял такие объекты с ошибкой
--  «Geometry has Z dimension but column does not».
--
--  Ограничение снимается целиком, а не заменяется на GeometryZ: в одной таблице
--  лежат результаты и плоской задачи, и задачи по глубине. Система координат
--  задаётся приложением при записи и проверяется тестом выгрузки.
-- =====================================================================================

ALTER TABLE variant_feature
    ALTER COLUMN geom TYPE geometry USING geom;

COMMENT ON COLUMN variant_feature.geom IS
    'Геометрия в WGS 84; с Z-координатами в режиме расчёта по глубине';
